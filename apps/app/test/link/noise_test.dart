import 'dart:convert';
import 'dart:typed_data';

import 'package:flutter_test/flutter_test.dart';
import 'package:pixelsky_app/link/link.dart';
import 'package:pixelsky_app/link/noise.dart' show x25519;

import 'fixtures.dart';

Keypair keypair(String privateHex) => keypairFrom(hex(privateHex));

void main() {
  group('official Noise KK vectors', () {
    for (final v in cases(fixture('noise_vectors.json'), 'vectors')) {
      test(v['protocol_name'], () {
        expect(v['protocol_name'], 'Noise_KK_25519_ChaChaPoly_SHA256');
        final i = Initiator(
          local: keypair(v['init_static']),
          remote: hex(v['init_remote_static']),
          ephemeral: keypair(v['init_ephemeral']),
          prologue: hex(v['init_prologue']),
        );
        final r = Responder(
          local: keypair(v['resp_static']),
          remote: hex(v['resp_remote_static']),
          ephemeral: keypair(v['resp_ephemeral']),
          prologue: hex(v['resp_prologue']),
        );
        final messages = cases(v, 'messages');
        final m1 = messages[0], m2 = messages[1];
        final c1 = i.writeMessage1(hex(m1['payload']));
        expect(toHex(c1), m1['ciphertext']);
        expect(toHex(r.readMessage1(c1)), m1['payload']);
        final w2 = r.writeMessage2(hex(m2['payload']));
        expect(toHex(w2.message), m2['ciphertext']);
        final r2 = i.readMessage2(w2.message);
        expect(toHex(r2.payload), m2['payload']);
        expect(toHex(r2.result.hash), v['handshake_hash']);
        expect(toHex(w2.result.hash), v['handshake_hash']);
        for (var k = 2; k < messages.length; k++) {
          final (from, to) = k % 2 == 0
              ? (r2.result, w2.result)
              : (w2.result, r2.result);
          final m = messages[k];
          final sealed = from.send.seal(hex(m['payload']));
          expect(toHex(sealed), m['ciphertext']);
          expect(toHex(to.receive.open(sealed)), m['payload']);
        }
      });
    }
  });

  final f = fixture('link_sessions.json');

  test('x25519 matches noble, including low-order rejection', () {
    for (final c in cases(f, 'x25519')) {
      final scalar = hex(c['scalar']), u = hex(c['u']);
      if (c.containsKey('error')) {
        expect(
          () => x25519(scalar, u),
          throwsLink(c['error']),
          reason: c['name'],
        );
      } else {
        expect(toHex(x25519(scalar, u)), c['out'], reason: c['name']);
      }
    }
  });

  test('derives the same public keys as TS', () {
    for (final c in cases(f, 'keypairs')) {
      expect(toHex(keypair(c['private']).publicKey), c['public']);
    }
  });

  group('sessions generated by TS', () {
    for (final s in cases(f, 'sessions')) {
      test(s['name'], () {
        final ini = s['initiator'] as Map<String, dynamic>;
        final res = s['responder'] as Map<String, dynamic>;
        Keypair key(Map<String, dynamic> side, String which) {
          final k = side[which] as Map<String, dynamic>;
          final pair = keypair(k['private']);
          expect(toHex(pair.publicKey), k['public']);
          return pair;
        }

        final prologue = hex(s['prologue']);
        final i = Initiator(
          local: key(ini, 'static'),
          remote: hex(ini['remote_static']),
          ephemeral: key(ini, 'ephemeral'),
          prologue: prologue,
        );
        final r = Responder(
          local: key(res, 'static'),
          remote: hex(res['remote_static']),
          ephemeral: key(res, 'ephemeral'),
          prologue: prologue,
        );
        final m1 = s['message1'] as Map<String, dynamic>;
        final m2 = s['message2'] as Map<String, dynamic>;
        final c1 = i.writeMessage1(hex(m1['payload']));
        expect(toHex(c1), m1['message']);
        expect(toHex(r.readMessage1(c1)), m1['payload']);
        final w2 = r.writeMessage2(hex(m2['payload']));
        expect(toHex(w2.message), m2['message']);
        final r2 = i.readMessage2(w2.message);
        expect(toHex(r2.payload), m2['payload']);
        expect(toHex(r2.result.hash), s['handshake_hash']);
        expect(toHex(w2.result.hash), s['handshake_hash']);

        // 双方算出的密钥和 TS 记下的一样：用记下的密钥另建一份，和握手得到的逐条比密文
        final k = s['keys'] as Map<String, dynamic>;
        final derived = {'initiator': r2.result, 'responder': w2.result};
        final recorded = {
          'initiator': (
            send: CipherState(hex(k['initiator_send'])),
            receive: CipherState(hex(k['initiator_receive'])),
          ),
          'responder': (
            send: CipherState(hex(k['responder_send'])),
            receive: CipherState(hex(k['responder_receive'])),
          ),
        };
        expect(k['initiator_send'], k['responder_receive']);
        expect(k['initiator_receive'], k['responder_send']);
        for (final t in cases(s, 'transport')) {
          final from = t['from'] as String;
          final to = from == 'initiator' ? 'responder' : 'initiator';
          final payload = hex(t['payload']);
          expect(toHex(derived[from]!.send.seal(payload)), t['ciphertext']);
          expect(toHex(recorded[from]!.send.seal(payload)), t['ciphertext']);
          final sealed = hex(t['ciphertext']);
          expect(toHex(derived[to]!.receive.open(sealed)), t['payload']);
          expect(toHex(recorded[to]!.receive.open(sealed)), t['payload']);
        }
      });
    }
  });

  test('handshake failures match TS', () {
    for (final c in cases(f, 'handshake_failures')) {
      final name = '${c['kind']} ${c['name']}';
      switch (c['kind']) {
        case 'read1':
          final o = c['responder'] as Map<String, dynamic>;
          final r = Responder(
            local: keypair(o['static_private']),
            remote: hex(o['remote_static']),
            ephemeral: keypair(o['ephemeral_private']),
            prologue: hex(o['prologue']),
          );
          expect(
            () => r.readMessage1(hex(c['message'])),
            throwsLink(c['error']),
            reason: name,
          );
        case 'read2':
          final o = c['initiator'] as Map<String, dynamic>;
          final i = Initiator(
            local: keypair(o['static_private']),
            remote: hex(o['remote_static']),
            ephemeral: keypair(o['ephemeral_private']),
            prologue: hex(o['prologue']),
          )..writeMessage1();
          expect(
            () => i.readMessage2(hex(c['message'])),
            throwsLink(c['error']),
            reason: name,
          );
        case 'write1':
          final o = c['initiator'] as Map<String, dynamic>;
          Initiator make() => Initiator(
            local: keypair(o['static_private']),
            remote: hex(o['remote_static']),
            ephemeral: keypair(o['ephemeral_private']),
            prologue: hex(o['prologue']),
          );
          if (c['at'] == 'construct') {
            expect(make, throwsLink(c['error']), reason: name);
          } else {
            final i = make();
            expect(i.writeMessage1, throwsLink(c['error']), reason: name);
          }
        default:
          fail('unknown kind $name');
      }
    }
  });

  group('Dart initiator and responder', () {
    ({HandshakeResult phone, HandshakeResult desktop}) session() {
      final phone = generateKeypair(), desk = generateKeypair();
      final i = Initiator(
        local: phone,
        remote: desk.publicKey,
        prologue: prologue,
      );
      final r = Responder(
        local: desk,
        remote: phone.publicKey,
        prologue: prologue,
      );
      r.readMessage1(i.writeMessage1());
      final w2 = r.writeMessage2();
      return (phone: i.readMessage2(w2.message).result, desktop: w2.result);
    }

    test('handshake and exchange messages both ways', () {
      final s = session();
      expect(s.phone.hash, s.desktop.hash);
      for (var n = 0; n < 3; n++) {
        final up = utf8.encode('上行 $n');
        expect(s.desktop.receive.open(s.phone.send.seal(up)), up);
        final down = utf8.encode('down $n 😀');
        expect(s.phone.receive.open(s.desktop.send.seal(down)), down);
      }
    });

    test('rejects a phone or desktop holding the wrong long-term key', () {
      final phone = generateKeypair(),
          desk = generateKeypair(),
          mallory = generateKeypair();
      final fake = Initiator(local: mallory, remote: desk.publicKey);
      expect(
        () => Responder(
          local: desk,
          remote: phone.publicKey,
        ).readMessage1(fake.writeMessage1()),
        throwsLink('LINK_HANDSHAKE_FAILED'),
      );
      final i = Initiator(local: phone, remote: desk.publicKey);
      expect(
        () => Responder(
          local: mallory,
          remote: phone.publicKey,
        ).readMessage1(i.writeMessage1()),
        throwsLink('LINK_HANDSHAKE_FAILED'),
      );
    });

    test(
      'rejects tampered and replayed frames without advancing the counter',
      () {
        final s = session();
        final a = s.phone.send.seal(utf8.encode('a'));
        final b = s.phone.send.seal(utf8.encode('b'));
        final tampered = Uint8List.fromList(a)..[3] ^= 1;
        expect(
          () => s.desktop.receive.open(tampered),
          throwsLink('LINK_DECRYPT_FAILED'),
        );
        expect(s.desktop.receive.open(a), utf8.encode('a'));
        expect(
          () => s.desktop.receive.open(a),
          throwsLink('LINK_DECRYPT_FAILED'),
        );
        expect(
          () => s.desktop.receive.open(Uint8List(15)),
          throwsLink('LINK_DECRYPT_FAILED'),
        );
        expect(s.desktop.receive.open(b), utf8.encode('b'));
      },
    );

    test('refuses messages in the wrong state or of the wrong size', () {
      final phone = generateKeypair(), desk = generateKeypair();
      final i = Initiator(local: phone, remote: desk.publicKey);
      expect(
        () => i.readMessage2(Uint8List(48)),
        throwsLink('LINK_HANDSHAKE_FAILED'),
      );
      final m1 = i.writeMessage1();
      expect(i.writeMessage1, throwsLink('LINK_HANDSHAKE_FAILED'));
      final r = Responder(local: desk, remote: phone.publicKey);
      expect(r.writeMessage2, throwsLink('LINK_HANDSHAKE_FAILED'));
      expect(
        () => Responder(
          local: desk,
          remote: phone.publicKey,
        ).readMessage1(Uint8List(10)),
        throwsLink('LINK_HANDSHAKE_FAILED'),
      );
      r.readMessage1(m1);
      expect(() => r.readMessage1(m1), throwsLink('LINK_HANDSHAKE_FAILED'));
      final m2 = r.writeMessage2().message;
      expect(r.writeMessage2, throwsLink('LINK_HANDSHAKE_FAILED'));
      i.readMessage2(m2);
      expect(() => i.readMessage2(m2), throwsLink('LINK_HANDSHAKE_FAILED'));
      expect(
        () => Initiator(local: phone, remote: Uint8List(5)),
        throwsLink('LINK_HANDSHAKE_FAILED'),
      );
    });
  });
}
